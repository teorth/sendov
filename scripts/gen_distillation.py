def coefficients(m, j):
    """Ascending powers, independently checked against the actual Lean definitions."""
    if j == 0:
        return [43740*m*(13*m-36), 972*(743*m*m-3330*m-2160),
                486*(665*m*m-4752*m-9360), 1134*(49*m*m-566*m-3600),
                12*(103*m*m-1323*m-161676), -377*m*m+22092*m-514512,
                2*(1363*m-36072), -4176]
    if j == 1:
        return [-14580*m*(15*m*m-17*m-204), -648*(450*m**3-934*m*m-11655*m-1620),
                -216*(660*m**3-2164*m*m-37581*m-6480),
                -216*(140*m**3-609*m*m-21974*m-2610),
                -3*(783*m**3-m*m-538848*m+6048),
                -2*(2914*m*m-158961*m+34992), -4*(174*m*m-8279*m+4392), 1392*(m-1)]
    if j == 2:
        return [-810*m*(m-3), -540*(m*m-7*m-3), -3*(27*m*m-565*m-720),
                2*(110*m+453), 116]
    raise ValueError('component must be 0, 1 or 2')

def certificate(p, a, b):
    """scale*p(x) = sum cs[i]*(x-a)^i*(b-x)^(n-i), exact rationals."""
    if not p:
        raise ValueError('empty polynomial data')
    if not a < b:
        raise ValueError('nonempty interval required')
    n = len(p)-1
    h = b-a
    q = [sum(F(p[i])*comb(i,k)*a**(i-k)*h**k for i in range(k,n+1)) for k in range(n+1)]
    cs = [sum(q[k]*F(comb(j,k),comb(n,k)) for k in range(j+1))*comb(n,j)/h**n for j in range(n+1)]
    scale = lcm(*(c.denominator for c in cs))
    ns = [int(c*scale) for c in cs]
    common = gcd(scale, gcd(*ns)) if len(ns)>1 else gcd(scale, ns[0])
    return scale//common, [c//common for c in ns]

def sign_cover(p, a, b):
    """One certificate for the entire flank; fail rather than grow a subdivision."""
    scale, cs = certificate(p,a,b)
    if min(cs) >= 0 and cs[0] > 0 and cs[-1] > 0:
        return [(a,b,scale,cs)]
    raise ValueError(f'no single strictly positive certificate on [{a},{b}]')

def validate_cover(intervals, a, b):
    if not intervals or intervals[0][0] != a or intervals[-1][1] != b:
        raise ValueError('missing sign region at boundary')
    cursor = a
    for lo,hi in intervals:
        if lo != cursor or not lo < hi:
            raise ValueError('sign coverage has gap, overlap or reversal')
        cursor = hi

def rat(x):
    x = F(x)
    return str(x.numerator) if x.denominator == 1 else f'({x.numerator} / {x.denominator})'

def signed(j,m,side):
    positive = (j == 0) == (side == 'left')
    return ('' if positive else '-')+f'distillCritical{j} {m} x'

def sign_source(m,j,side,a,b):
    name=f'sign_{j}_{side}'
    target=signed(j,m,side)
    if a == b:
        return f'''private lemma {name} (x : ℝ) (hx : x ∈ Set.Ioo {rat(a)} {rat(b)}) :
    0 ≤ {target} := by
  exact False.elim (lt_irrefl {rat(a)} (hx.1.trans hx.2))

''', 0
    p=coefficients(m,j)
    if target.startswith('-'):
        p=[-c for c in p]
    cells=sign_cover(p,a,b)
    validate_cover([(v[0],v[1]) for v in cells],a,b)
    [(lo,hi,scale,cs)]=cells
    data=textwrap.fill('['+', '.join(map(str,cs))+']', width=92,
                       initial_indent='    ', subsequent_indent='     ')
    return f'''private lemma {name} (x : ℝ) (hx : x ∈ Set.Ioo {rat(a)} {rat(b)}) :
    0 ≤ {target} := by
  refine (BernsteinCert.coeffs_pos
{data}
    (lo := {rat(lo)}) (hi := {rat(hi)}) (s := {scale})
    (by norm_num) (by norm_num) ⟨hx.1.le, hx.2.le⟩ (by decide) (by decide) ?_).le
  unfold distillCritical{j}
  norm_num only [BernsteinCert.coeffTree, BernsteinCert.Cert.eval,
    List.length_cons, List.length_nil]
  bernstein_ring (x - {rat(lo)}) ({rat(hi)} - x)

''', 1

def row_source(row):
    m=row['m']; d=min(F(17),F(m,2))
    s='import Sendov.Common.DistillationCriticalFinite\nimport Sendov.Common.BernsteinList\n\n'
    s+='/-! Fixed paper budgets; low-degree sign certificates, not whole-domain T subdivisions.\nGenerated by scripts/gen_distillation.py. See the shared helper for provenance. -/\n\n'
    s+=f'namespace Sendov\nnamespace CriticalRow{m}\n\n'
    for c in row['components']:
        j=c['index']; lo=F(c['lo']); hi=F(c['hi']); u=F(c['u'],1000)
        for side,a,b in [('left',F(0),lo),('right',hi,d)]:
            source, _ = sign_source(m,j,side,a,b)
            s += source
        s+=f'''theorem component{j} (α : ℝ) (hα : 0 ≤ α) (hd : α ≤ {rat(d)}) :
    distillT{j} {m} α ≤ {rat(u)} := by
  apply distillT{j}_le_of_critical (l := {rat(lo)}) (r := {rat(hi)}) (d := {rat(d)})
'''
        if j:
            s+=f'    {m-3} (by norm_num) (by norm_num)\n'
        s+='    (by norm_num) (by norm_num) (by norm_num) (by norm_num) (by norm_num)\n'
        s+=f'    sign_{j}_left sign_{j}_right ?_ ⟨hα, hd⟩\n'
        s+='  norm_num [distillKappa, distillRatio, distillNode, cubicPolarEnvelope]\n\n'
    s+=f'end CriticalRow{m}\n\n'
    total=rat(row['total'])
    s+=f'''theorem distillFinite_{m} (α : ℝ) (hα : 0 ≤ α) (hd : α ≤ {rat(d)}) :
    distillEBudget {m} + distillT0 {m} α + distillT1 {m} α + distillT2 {m} α ≤ {total} := by
  have h0 := CriticalRow{m}.component0 α hα hd
  have h1 := CriticalRow{m}.component1 α hα hd
  have h2 := CriticalRow{m}.component2 α hα hd
  norm_num [distillEBudget] at *
  linarith

theorem distillFiniteBound_{m} : ({total} : ℝ) < 199 / 200 := by norm_num

'''
    s+='end Sendov\n'
    return s

def aggregate_source():
    s=''.join(f'import Sendov.DistillationFinite.Row{m}\n' for m in ROWS)
    s+=f'''
/-! Exact finite-domain critical-bracket closure. Fixed original paper budgets;
see DistillationCriticalFinite for attribution. No sampled truth or global T grid. -/
namespace Sendov

theorem distillFinite_components {{m : ℕ}} (hm : 5 ≤ m) (hm63 : m ≤ {FINITE_ROWS[-1]})
    {{α : ℝ}} (hα : 0 ≤ α) (hαm : α ≤ (m : ℝ) / 2) (h17 : α ≤ 17) :
    distillEBudget m + distillT0 m α + distillT1 m α + distillT2 m α < 199 / 200 := by
  interval_cases m
'''
    for m in FINITE_ROWS:
        s+=f'  · exact (distillFinite_{m} α hα (by linarith)).trans_lt distillFiniteBound_{m}\n'
    s+=f'''
theorem distillFinite_scalar {{m : ℕ}} (hm : 5 ≤ m) (hm63 : m ≤ {FINITE_ROWS[-1]})
    {{α : ℝ}} (hα : 0 < α) (hαm : α ≤ (m : ℝ) / 2) (h17 : α ≤ 17) :
    scalarObstruction m α (cubicPolarEnvelope α) < 199 / 200 := by
  have hmR : (5 : ℝ) ≤ m := by exact_mod_cast hm
  exact (distillScalar_le_majorant hmR hα (by linarith)).trans_lt
    (distillFinite_components hm hm63 hα.le hαm h17)

end Sendov
'''
    return s


def require_empty_output(output):
    if output.is_symlink() or (output.exists() and
            (not output.is_dir() or any(output.iterdir()))):
        raise ValueError('output must be a new or empty directory (not a symlink)')


def generate(output, table=TABLE):
    output = Path(output).absolute()
    require_empty_output(output)
    rows = load_table(table, coefficients)
    rendered = {f'Sendov/DistillationFinite/Row{r["m"]}.lean': row_source(r)
                for r in rows}
    rendered['Sendov/Common/DistillationFinite.lean'] = aggregate_source()
    # All exact calculations and row rendering precede staging. Only the grouped
    # snapshot is published; individual rows are temporary packaging inputs.
    output.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix='.distillation-', dir=output.parent) as temporary:
        work = Path(temporary)
        raw = work / 'rows'
        for rel, text in rendered.items():
            target = raw / rel
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(text, encoding='utf-8', newline='\n')
        result = bundle(raw, work / 'grouped', size=8)
        require_empty_output(output)
        os.replace(work / 'grouped', output)
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True,
                        help='new or empty output directory; never the project source tree')
    parser.add_argument('--table', type=Path, default=TABLE,
                        help='exact table JSON (default: project data/paper_certificate_table.json)')
    args = parser.parse_args()
    try:
        result = generate(args.output, args.table)
    except (ValueError, OSError) as error:
        parser.exit(1, f'error: {error}\n')
    print(json.dumps(result, indent=2))


if __name__ == '__main__':
    main()
